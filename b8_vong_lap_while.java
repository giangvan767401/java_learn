// while kiem tra dieu kien truoc roi moi thuc hien vong lap
// do while thuc hien vong lap roi moi kiem tra dieu kien
public class b8_vong_lap_while {
    public static void main(String[] args) {
        int i = 1;
        while (i < 10) {
            System.out.println(i);
            i++;
        }

        int j = 1;
        do {
            System.out.println(j);
            j++;
        } while (j < 10);
    }
}
